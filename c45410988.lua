--レッドアイズ・トランスマイグレーション
-- 效果：
-- 「真红王」的降临必需。
-- ①：从自己的手卡·场上把等级合计直到8以上的怪兽解放或者作为解放的代替而把自己墓地的「真红眼」怪兽除外，从手卡把「真红王」仪式召唤。
function c45410988.initial_effect(c)
	-- 为「真红眼转生」这张卡添加仪式召唤效果：以卡号19025379（真红王）为仪式召唤的仪式怪兽，素材过滤条件使用c45410988.mfilter，且仪式素材等级合计可以超过仪式怪兽的原本等级（合计直到8以上），并支持用自己手卡·场上的怪兽解放或将墓地中的「真红眼」怪兽作为解放的代替除外来进行仪式召唤。
	aux.AddRitualProcGreaterCode(c,19025379,nil,c45410988.mfilter)
end
-- 定义素材过滤函数：判断传入的卡是否为「真红眼」字段（卡名含有0x3b对应的文本「真红眼」），返回真则该卡可作为仪式召唤的解放/代替素材。
function c45410988.mfilter(c)
	return c:IsSetCard(0x3b)
end
